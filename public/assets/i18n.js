let currentLocale = 'en';

function setLocale(locale) {
  currentLocale = I18N[locale] ? locale : 'en';
  document.documentElement.setAttribute('lang', currentLocale);
}

/** Best match for the browser's preferred languages, English otherwise. */
function detectLocale() {
  for (const tag of navigator.languages || [navigator.language || 'en']) {
    const base = String(tag).toLowerCase().split('-')[0];
    if (I18N[base]) return base;
  }
  return 'en';
}

/** Translate a key, replacing {placeholders} with the given values. */
function t(key, vars) {
  const table = I18N[currentLocale] || I18N.en;
  let value = table[key] ?? I18N.en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, replacement);
    }
  }
  return value;
}

/** Fill every [data-t] element in the document with its translation, and every
 *  [data-tp] field with its placeholder. */
function applyTranslations(root = document) {
  root.querySelectorAll('[data-t]').forEach((el) => {
    el.textContent = t(el.dataset.t);
  });
  root.querySelectorAll('[data-tp]').forEach((el) => {
    el.placeholder = t(el.dataset.tp);
  });
}

